    window.BDGeo = {
        data: BD_GEO_DATA,

        getDivisions: function() {
            return Object.keys(BD_GEO_DATA).map(key => ({
                key: key,
                name_bn: BD_GEO_DATA[key].name_bn
            }));
        },

        getDistricts: function(divisionKey) {
            if (!divisionKey || !BD_GEO_DATA[divisionKey]) return [];
            const districtsObj = BD_GEO_DATA[divisionKey].districts;
            return Object.keys(districtsObj).map(key => ({
                key: key,
                name_bn: districtsObj[key].name_bn,
                upazilas: districtsObj[key].upazilas
            }));
        },

        getUpazilas: function(divisionKey, districtKey) {
            if (!divisionKey || !districtKey || !BD_GEO_DATA[divisionKey]) return [];
            const district = BD_GEO_DATA[divisionKey].districts[districtKey];
            return district ? district.upazilas : [];
        },

        findDivisionByDistrict: function(districtKeyOrName) {
            if (!districtKeyOrName) return null;
            const search = districtKeyOrName.trim().toLowerCase();
            for (const divKey in BD_GEO_DATA) {
                const dists = BD_GEO_DATA[divKey].districts;
                for (const distKey in dists) {
                    if (distKey.toLowerCase() === search || dists[distKey].name_bn.toLowerCase() === search) {
                        return { divisionKey: divKey, districtKey: distKey };
                    }
                }
            }
            return null;
        }
    };
